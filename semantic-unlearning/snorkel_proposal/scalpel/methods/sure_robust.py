class SureRobust(Method):
    card = MethodCard("sure_r", "detect_then_edit",
                      "SURE with base-model-generated request views, fuzzy subject eligibility, same-subject "
                      "hard negatives, rows refined on every routed view; cached boundary-aware decoding",
                      runtime_components=["router_hooks"], reference="this repository", decode="hf")

    def __init__(self, preset: str = "sure_r", **kwargs):
        merged = {**PRESETS[preset], **kwargs}
        super().__init__(**merged)
        self.preset = preset
        bake = arg(self.args, "bake", 0, int)
        self.card = MethodCard(preset, "detect_then_edit" if not bake else "locate_edit",
                               SureRobust.card.description + (" (rows baked into down_proj)" if bake else ""),
                               runtime_components=[] if bake else ["router_hooks"],
                               reference="this repository", decode="hf")

    def unlearn(self, base, requests, allowed_retain, ctx):
        a = self.args
        root = Path(a.get("root", SEMANTIC_ROOT)).resolve()
        work = Path(a.get("work_dir", f"outputs/scalpel_{self.preset}")).resolve()
        layer = arg(a, "layer", 19, int)
        device = a.get("device", "cuda")
        fit_device = a.get("fit_device", "cpu" if device == "mps" else device)
        model_path = a["model_path"]
        kinds = [k for k in str(a.get("views", "")).split(",") if k]
        fuzzy = arg(a, "fuzzy", 1, int)
        hardneg = arg(a, "hardneg", 0, int)
        free = a.get("free_fire_logit")
        refine = str(a.get("refine", "suppress"))
        bake = arg(a, "bake", 0, int)
        updates = arg(a, "row_updates", 60, int)
        renderer = ctx.renderer
        report: Dict[str, object] = {"preset": self.preset, "layer": layer, "views": kinds, "fuzzy": bool(fuzzy),
                                     "hardneg": bool(hardneg), "free_fire_logit": free, "refine": refine, "bake": bool(bake)}

        data = export_multifact(requests, work / "data", ctx.seed, model_path)
        visible = json.loads((data / "training_visible_forget.json").read_text())
        L = f"L{layer:02d}"
        prep, router, rows_dir = work / L / "prep", work / L / "router", work / L / "rows"
        py = [sys.executable, "-u"]
        env = {**os.environ, "PYTHONPATH": str(root / "scripts") + os.pathsep + os.environ.get("PYTHONPATH", "")}

        def run(out, cmd):
            if (out / "fact_association_embeddings.pt").exists():
                return
            ctx.log("[sure_r] " + " ".join(str(c) for c in cmd))
            with gpu_released(base.hf):
                subprocess.run([str(c) for c in cmd], cwd=str(root), env=env, check=True)

        run(prep, py + [root / "scripts/prepare_multifact_association_source.py", "--model-path", model_path,
                        "--training-visible", data / "training_visible_forget.json",
                        "--split-manifest", data / "split_manifest.json", "--output-dir", prep,
                        "--layer", layer, "--device", device, "--local-files-only"])
        manifest = json.loads((prep / "association_manifest.json").read_text())
        case_to_fact = {str(k): v for k, v in manifest["atomic_case_to_association_id"].items()}
        req_of_fact = {case_to_fact[str(rec["case_id"])]: rec["scalpel_request_id"] for rec in visible}

        views, view_stats = make_views(base, renderer, requests, kinds, log=ctx.log) if kinds else ({}, {})
        negatives = make_hard_negatives(base, renderer, requests, log=ctx.log) if hardneg else {}
        report["views_stats"] = view_stats
        if not (router / "fact_association_embeddings.pt").exists():
            report["router_inputs"] = write_router_inputs(prep, req_of_fact, views, negatives)
        fit_args = ["--subject-match", "fuzzy" if fuzzy else "exact"]
        if hardneg:
            fit_args += ["--extra-negatives", prep / "extra_negatives.json"]
        if free is not None:
            fit_args += ["--unmasked-fit", "--free-fire-logit", float(free)]
        run(router, py + [root / "scripts/fit_linear_router.py", "--run-dir", prep, "--output-dir", router,
                          "--device", device, "--fit-device", fit_device, "--local-files-only",
                          "--threshold-policy", "global", "--decision-rule", "calibrated_bias",
                          "--min-recall", "0.98", "--threshold-placement-fraction", "0.1", *fit_args,
                          "--pca-dims", "0,64,256", "--positives-per-fact", "0", "--negatives-per-fact", "0"])   # SURE-R's tested recipe
        run(rows_dir, py + [root / "scripts/train_direct_linear_router_rows.py", "--dataset", "multifact",
                            "--router-dir", router, "--output-dir", rows_dir, "--training-route", "router",
                            "--norm-scale", "1", "--row-updates-per-fact", updates,
                            "--max-training-seconds", int(ctx.max_seconds), "--device", device, "--local-files-only"])

        sys.path.insert(0, str(root / "scripts"))
        from linear_router import load_router_artifact  # noqa: E402
        artifact = torch.load(rows_dir / "fact_association_embeddings.pt", map_location="cpu", weights_only=False)
        assoc, bank = load_router_artifact(base.hf, artifact)
        bank.tokenizer = base.tokenizer
        runtime = _SureRuntime(assoc, bank).eval()
        facts = artifact["facts"]
        fact_index = {f["id"]: i for i, f in enumerate(facts)}
        req_by_id = {r.request_id: r for r in requests}

        # every context of a fact: its request + its validated views; keep those routed to it
        contexts: Dict[int, List[Probe]] = {}
        for fid, rid in req_of_fact.items():
            r = req_by_id.get(rid)
            if r is None or fid not in fact_index:
                continue
            ps = [Probe(probe_id=f"req/{rid}", role="forget", family="direct", fact_id=r.fact_id, prompt=r.prompt,
                        answer=r.answer, format=r.format, request_id=rid, subject=r.subject, relation=r.relation)]
            ps += [v.probe for v in views.get(rid, [])]
            contexts[fact_index[fid]] = ps
        routed = self._route(runtime, renderer, contexts)
        report["contexts"] = {"total": sum(len(v) for v in contexts.values()),
                              "routed_to_own_row": sum(len(v) for v in routed.values())}
        if refine in ("suppress", "idk"):
            rep_layer = json.loads((rows_dir / "association_manifest.json").read_text()).get("layer_representation", {})
            report["refine"] = refine_rows(runtime, renderer, routed, refine,
                                           boundary_norm=float(rep_layer.get("boundary_norm_median", 1.0)),
                                           max_sweeps=arg(a, "refine_sweeps", 60, int), log=ctx.log)
        self._report = {**report, "work_dir": str(work), "facts": len(facts)}

        if bake:
            cov = wikipedia_covariance(base.hf, base.tokenizer, layer, a.get("mom2_dataset"), log=ctx.log)
            lam = float(a.get("lam", 15000.0))       # MEMIT's mom2_update_weight
            self._report["bake"] = bake_rows(runtime, renderer, routed, lam=lam, cov=cov, log=ctx.log)
            return ModelHandle(model=base.hf, tokenizer=base.tokenizer, hf=base.hf)

        subj_to_req = {r["requested_rewrite"]["subject"]: r["scalpel_request_id"] for r in visible}

        def route(prompts):
            out = []
            tok = base.tokenizer
            for t in prompts:
                special = not (tok.bos_token and t.startswith(tok.bos_token))   # chat text carries its BOS
                ids = tok(t, return_tensors="pt", add_special_tokens=special)["input_ids"].to(base.device)
                runtime(input_ids=ids, attention_mask=torch.ones_like(ids), prompt_lengths=[ids.shape[1]])
                hit = (bank.last_active_fact_indices or [[]])[0]
                out.append(subj_to_req.get(facts[hit[0]].get("subject")) if hit else None)
            return out

        def strip():
            bank.close()
            return ModelHandle(model=base.hf, tokenizer=base.tokenizer, hf=base.hf)

        return ModelHandle(model=runtime, tokenizer=base.tokenizer, hf=base.hf, runtime_components=["router_hooks"],
                           strip=strip, route=route, decode="cached_boundary", needs_prompt_lengths=True,
                           lens_module=runtime)

    @staticmethod
    @torch.no_grad()
    def _route(runtime, renderer, contexts):
        out = {}
        for fi, probes in contexts.items():
            keep = []
            for p in probes:
                ids = torch.tensor([renderer.encode_prompt(p)], device=next(runtime.assoc.base_model.parameters()).device)
                runtime(input_ids=ids, attention_mask=torch.ones_like(ids), prompt_lengths=[ids.shape[1]])
                hit = (runtime.bank.last_active_fact_indices or [[]])[0]
                if hit and hit[0] == fi:
                    keep.append(p)
            if keep:
                out[fi] = keep
        return out


