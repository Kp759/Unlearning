"""SURE-R: the repository's SURE with the robustness fixes the first SCALPEL pilot pointed to.

Each fix is a switch, so the benchmark can measure it alone (see PRESETS):

    views     the router (and the rows) also learn base-model-generated views of each request:
              paraphrases, a direct question, translations, a multi-turn follow-up that refers to
              the subject by pronoun. Rendered exactly as the deployed model sees them (chat
              template for questions and chats). A view is kept only if the base model answers
              it with the request's answer. Nothing comes from SCALPEL's probe templates: every
              view is the base model's own rewrite of the request.
    fuzzy     subject eligibility also matches the subject's words in the decoded prompt up to
              case, accents, spacing and one edit per word (linear_router.fuzzy_subject_in_text).
    hardneg   extra negatives per head: other questions / sentences about the same subject,
              generated by the base model from the request (locality guard for fuzzy + views).
    free      experimental subject-free firing: heads fitted against every prompt, and a head
              may fire without an eligible subject at a deployed logit >= free_fire_logit.
    refine    after SURE's own row training, rows are refined on every routed view toward the
              target: "suppress" (answer tokens below 1e-4) or "idk" (" I don't know." + EOS).
    bake      experimental: compile the rows into a closed-form edit of down_proj at SURE's
              layer (MEMIT's solve with the Wikipedia covariance; keys = the boundary MLP
              inputs of the routed views, values = the rows). No runtime component remains.
    decoding  KV-cached, batched, boundary-aware generation (identical tokens; tested).

    --method sure_r --method-arg model_path=M --method-arg layer=19 --method-arg device=cuda
"""
